function getLang() {
    return localStorage.getItem('mousescope_lang') || 'zh';
}

function setLang(lang) {
    localStorage.setItem('mousescope_lang', lang);
}

function apiErrorText(payload, fallback) {
    const data = (payload && typeof payload === 'object') ? payload : {};
    const safeFallback = String(fallback || '');
    if (getLang() === 'en') {
        return String(data.error_en || safeFallback || 'Operation failed. Check the inputs and try again.');
    }
    return String(data.error || safeFallback || '操作失败，请检查输入后重试。');
}

if (typeof window !== 'undefined') {
    window.apiErrorText = apiErrorText;
}

function applyLang(lang) {
    const dict = I18N[lang] || I18N['zh'];

    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        const val = dict[key];
        if (val === undefined) return;

        const attr = el.getAttribute('data-i18n-attr');
        if (attr) {
            el.setAttribute(attr, val);
        } else if (el.getAttribute('data-i18n-html') !== null) {
            el.innerHTML = val;
        } else {
            el.textContent = val;
        }
    });

    document.documentElement.lang = (lang === 'zh') ? 'zh-CN' : 'en';
    document.dispatchEvent(new CustomEvent('mousescope:langchange', { detail: { lang } }));
}

function applyPageI18n(pageDict, root) {
    const lang = getLang();
    const dict = (pageDict && (pageDict[lang] || pageDict.zh)) || {};
    const scope = root || document;

    scope.querySelectorAll('[data-page-i18n]').forEach(el => {
        const key = el.getAttribute('data-page-i18n');
        const val = dict[key];
        if (val === undefined) return;

        const attr = el.getAttribute('data-page-i18n-attr');
        if (attr) {
            el.setAttribute(attr, val);
        } else if (el.getAttribute('data-page-i18n-html') !== null) {
            el.innerHTML = val;
        } else {
            el.textContent = val;
        }
    });
}

if (typeof window !== 'undefined') {
    window.applyPageI18n = applyPageI18n;
}

function toggleLang() {
    const next = (getLang() === 'zh') ? 'en' : 'zh';
    setLang(next);
    applyLang(next);
}

document.addEventListener('DOMContentLoaded', function () {
    applyLang(getLang());
});
