// ─────────────────────────────────────────
function getLang() {
    return localStorage.getItem('mousescope_lang') || 'zh';
}

function setLang(lang) {
    localStorage.setItem('mousescope_lang', lang);
}

function applyLang(lang) {
    const dict = I18N[lang] || I18N['zh'];

    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        const val = dict[key];
        if (val === undefined) return;

        const attr = el.getAttribute('data-i18n-attr');
        if (attr) {
            el.setAttribute(attr, val);
        } else if (el.getAttribute('data-i18n-html') !== null) {
            el.innerHTML = val;
        } else {
            el.textContent = val;
        }
    });

    document.documentElement.lang = (lang === 'zh') ? 'zh-CN' : 'en';
    document.dispatchEvent(new CustomEvent('mousescope:langchange', { detail: { lang } }));
}

function toggleLang() {
    const next = (getLang() === 'zh') ? 'en' : 'zh';
    setLang(next);
    applyLang(next);
}

document.addEventListener('DOMContentLoaded', function () {
    applyLang(getLang());
});
